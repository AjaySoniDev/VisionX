"""Deterministic vector stress scenarios; no images, people or field data."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from vxn_ramnet.algorithms.similarity import l2_normalize_rows
from vxn_ramnet.io.atomic import atomic_write_json
from vxn_ramnet.io.checksums import sha256_file
from vxn_ramnet.io.npz import save_npz


def generate_synthetic_dataset(output: Path, *, seed: int = 2026) -> Path:
    if output.exists():
        raise FileExistsError("Synthetic dataset output exists; choose a new directory")
    rng = np.random.default_rng(seed)
    dimension = 64

    def vectors(count: int) -> np.ndarray:
        return l2_normalize_rows(rng.normal(size=(count, dimension)).astype(np.float32))

    common, junction, branch_a, branch_b = vectors(22), vectors(7), vectors(22), vectors(20)
    learning = np.vstack([common, junction, branch_a, branch_a[::-1], junction, branch_b])
    output.mkdir(parents=True)
    records = []

    def save(identifier: str, values: np.ndarray, label: str | None, split: str) -> dict:
        path = output / (identifier + ".npz")
        save_npz(path, {"embeddings": values, "flipped_embeddings": values.copy()})
        return {
            "id": identifier,
            "path": path.name,
            "sha256": sha256_file(path),
            "session_id": identifier,
            "split": split,
            "expected_label": label,
        }

    learning_record = save("synthetic-learning", learning, None, "synthetic")
    for label, count in (("BRANCH_A", 24), ("BRANCH_B", 24), ("UNKNOWN", 24), ("AMBIGUOUS", 12)):
        for index in range(count):
            prefix = common[np.linspace(0, len(common) - 1, 20, dtype=int)]
            if label == "UNKNOWN":
                query = vectors(60)
            else:
                ai = np.linspace(0, len(branch_a) - 1, 40, dtype=int)
                bi = np.linspace(0, len(branch_b) - 1, 40, dtype=int)
                if label == "BRANCH_A":
                    suffix = branch_a[ai]
                elif label == "BRANCH_B":
                    suffix = branch_b[bi]
                else:
                    suffix = l2_normalize_rows(branch_a[ai] + branch_b[bi])
                values = np.vstack([prefix, suffix])
                # Fresh perturbation per query; noise level is predeclared, not tuned.
                query = l2_normalize_rows(values + rng.normal(0, 0.04, values.shape).astype(np.float32))
            records.append(save(f"synthetic-{label.lower()}-{index:02d}", query, label, "synthetic"))
    manifest = {
        "schema_version": "1.0.0",
        "dataset_id": "synthetic-stress-v1",
        "purpose": "synthetic",
        "root": ".",
        "provenance": f"Generated by vxn_ramnet.evaluation.synthetic; NumPy default_rng seed {seed}. 100 enrollment vectors, 84 queries of 60 vectors each. All simulated.",
        "encoder_provenance": "No visual encoder. Unit-normalized Gaussian 64-dimensional vectors; flipped descriptors equal original descriptors.",
        "learning": learning_record,
        "queries": records,
        "expected_events": {
            "first_junction_index": 25,
            "turnaround_index": 50,
            "return_junction_index": 76,
            "provenance": "Generator geometry: centers of repeated seven-vector junction; turnaround adjacent to repeated branch reversal",
        },
        "detection": {
            "first_junction_search": [0.15, 0.40],
            "return_junction_search": [0.60, 0.85],
            "expected_first_junction_ratio": 0.25,
            "expected_return_junction_ratio": 0.76,
            "junction_window": 2,
            "junction_memory_radius": 2,
            "min_junction_gap_ratio": 0.30,
        },
    }
    path = output / "manifest.json"
    atomic_write_json(path, manifest)
    return path
